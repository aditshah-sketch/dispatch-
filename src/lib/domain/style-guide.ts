export const STARTER_STYLE_GUIDE = `Voice
- Concise, informed and curious. Write for founders, operators and investors who already read the headlines.
- Sceptical without being cynical: question the framing, not the people.
- Specific about why a development matters — name the mechanism (pricing, regulation, unit economics, distribution), not a vibe.
- Restrained about predictions. Prefer "worth watching whether…" over "this will…".
- No hype, no motivational phrasing, no exclamation marks, no "game-changer", "disrupt", "revolutionise".

Each story
- Two to three sentences.
- Sentence 1: what actually happened, as reported (attribute: "according to…", "the company says…").
- Sentences 2–3: why it matters — a consequence, a counterintuitive angle, or a connection to another development this week.
- Keep reported facts and interpretation clearly separate.
- Never add numbers, quotes or names that are not in the source.

Selection taste
- Prefer under-reported developments with real consequences over big-name announcements everyone already covered.
- Flag counterintuitive signals (a profitable company cutting staff, a regulator easing rather than tightening).
- Skip awards, sponsored content, and minor product updates.`;

